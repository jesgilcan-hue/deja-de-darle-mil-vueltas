// 1. GENERADOR DE SUDOKUS 9x9 (MATEMÁTICO)
// ==========================================
export function generateSolvedSudoku() {
    const grid = [];
    for (let r = 0; r < 9; r++) {
        const row = [];
        for (let c = 0; c < 9; c++) {
            row.push(((r * 3 + Math.floor(r / 3) + c) % 9) + 1);
        }
        grid.push(row);
    }
    const digits = shuffle([1, 2, 3, 4, 5, 6, 7, 8, 9]);
    const map = {};
    for (let i = 0; i < 9; i++) map[i + 1] = digits[i];
    for (let r = 0; r < 9; r++) {
        for (let c = 0; c < 9; c++) grid[r][c] = map[grid[r][c]];
    }
    for (let b = 0; b < 3; b++) {
        const order = shuffle([0, 1, 2]);
        const orig = grid.slice(b * 3, b * 3 + 3);
        for (let i = 0; i < 3; i++) grid[b * 3 + i] = orig[order[i]];
    }
    for (let b = 0; b < 3; b++) {
        const order = shuffle([0, 1, 2]);
        for (let r = 0; r < 9; r++) {
            const orig = [grid[r][b * 3], grid[r][b * 3 + 1], grid[r][b * 3 + 2]];
            grid[r][b * 3] = orig[order[0]];
            grid[r][b * 3 + 1] = orig[order[1]];
            grid[r][b * 3 + 2] = orig[order[2]];
        }
    }
    if (Math.random() > 0.5) {
        const transposed = [];
        for (let c = 0; c < 9; c++) {
            const row = [];
            for (let r = 0; r < 9; r++) row.push(grid[r][c]);
            transposed.push(row);
        }
        return transposed;
    }
    return grid;
}

export function createSudokuPuzzle(solved, targetClues = 34) {
    const puzzle = solved.map(r => r.slice());
    const positions = [];
    for (let r = 0; r < 9; r++) {
        for (let c = 0; c < 9; c++) positions.push([r, c]);
    }
    const shuffledPos = shuffle(positions);
    let cluesCount = 81;
    for (let i = 0; i < shuffledPos.length; i++) {
        if (cluesCount <= targetClues) break;
        const [r, c] = shuffledPos[i];
        puzzle[r][c] = 0;
        cluesCount--;
    }
    return puzzle;
}

export function getSudokuTargetClues(diff) {
    if (diff === 'easy') return 38;
    if (diff === 'medium') return 32;
    return 28; // hard
}

